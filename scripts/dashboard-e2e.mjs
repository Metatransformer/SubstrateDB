import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { createServer } from 'node:net';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../dashboard/package.json', import.meta.url));
const { chromium } = require('playwright');
const directory = await mkdtemp(join(tmpdir(), 'substrate-dashboard-'));
const portServer = createServer();
await new Promise(resolve => portServer.listen(0, '127.0.0.1', resolve));
const port = portServer.address().port;
await new Promise(resolve => portServer.close(resolve));
const url = `http://127.0.0.1:${port}`;
const child = spawn(fileURLToPath(new URL('../target/debug/substrate', import.meta.url)), ['--dev', '--data', join(directory, 'db.redb'), '--listen', `127.0.0.1:${port}`], { stdio: ['ignore', 'pipe', 'pipe'] });
let logs = '';
child.stdout.on('data', chunk => { logs += chunk; });
child.stderr.on('data', chunk => { logs += chunk; });
let browser;
try {
  for (let i = 0; ; i++) {
    try { if ((await fetch(`${url}/health`)).ok) break; } catch {}
    if (i > 100 || child.exitCode !== null) throw new Error(`Runtime failed to start: ${logs}`);
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const nav = name => page.getByRole('navigation').getByRole('button', { name, exact: true }).click();
  async function action(button, name) {
    const waiting = page.waitForResponse(response => response.url().endsWith('/v1/command') && JSON.parse(response.request().postData()).action === name);
    await page.getByRole('button', { name: button, exact: true }).click();
    const response = await waiting;
    const body = await response.json();
    assert.equal(response.status(), 200, JSON.stringify(body));
    await page.waitForFunction(() => !document.querySelector('.result-state'));
    return body.result;
  }
  await page.goto(`${url}/dashboard`);
  await page.getByLabel('Admin credential').fill('incorrect');
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'unauthorized' }).waitFor();
  await page.getByRole('button', { name: 'Use local dev token' }).click();
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.getByRole('button', { name: 'Disconnect' }).waitFor();
  await nav('Documents');
  await page.getByLabel('Collection', { exact: true }).fill('articles');
  await page.getByLabel(/^Document ID/).fill('first');
  await page.getByLabel(/^Expected revision/).fill('0');
  await page.getByLabel('JSON value', { exact: true }).fill('{"title":"Browser test","status":"active"}');
  assert.equal((await action('Save document', 'document.put')).revision, 1);
  assert.equal((await action('Run query', 'document.query')).documents.length, 1);
  await page.getByRole('button', { name: 'Start watch' }).click();
  await page.locator('.json-result').filter({ hasText: '"snapshot"' }).waitFor();
  await page.getByLabel(/^Expected revision/).fill('1');
  await page.getByLabel('JSON value', { exact: true }).fill('{"title":"Updated browser test","status":"active"}');
  await action('Save document', 'document.put');
  await page.locator('.json-result').filter({ hasText: '"updated"' }).waitFor();
  await page.getByRole('button', { name: 'Stop watch' }).click();
  await nav('Queues');
  await page.getByLabel('Job ID', { exact: true }).fill('browser-job');
  await action('Enqueue', 'job.enqueue');
  assert.equal((await action('List jobs', 'job.list')).jobs[0].id, 'browser-job');
  await nav('Cache');
  await page.getByLabel('Key', { exact: true }).fill('browser-cache');
  await page.getByLabel('JSON value', { exact: true }).fill('false');
  await action('Set value', 'cache.set');
  assert.equal(await action('Get', 'cache.get'), false);
  await nav('Search');
  await action('Configure', 'vector.configure');
  await page.getByLabel('Document ID', { exact: true }).fill('first');
  await page.getByLabel('Source revision', { exact: true }).fill('2');
  await action('Submit vector', 'vector.upsert');
  await page.waitForTimeout(800);
  assert.equal((await action('Run search', 'search.query')).hits[0].id, 'first');
  await nav('Schedules');
  await page.getByLabel('Schedule ID', { exact: true }).fill('browser-cron');
  await action('Save schedule', 'schedule.put');
  assert.equal((await action('List schedules', 'schedule.list')).schedules[0].id, 'browser-cron');
  await nav('Events');
  assert.ok((await action('Read events', 'event.read')).events.length > 0);
  await nav('API Console');
  await action('Run command', 'scope.stats');
  await nav('Documentation');
  assert.ok((await page.locator('.docs-content').innerText()).includes('7432'));
  assert.equal((await page.request.get(`${url}/dashboard/docs/QUICKSTART.md`)).status(), 200);
  await nav('Documents');
  await action('Run query', 'document.query');
  await page.getByRole('button', { name: 'Disconnect' }).click();
  await page.getByLabel('Namespace', { exact: true }).fill('other');
  await page.getByRole('button', { name: 'Use local dev token' }).click();
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.getByRole('button', { name: 'Disconnect' }).waitFor();
  assert.equal(await page.getByRole('cell', { name: 'first', exact: true }).count(), 0);
  assert.deepEqual(await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage) })), { local: [], session: [] });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await nav('Overview');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.reload();
  await page.getByRole('button', { name: 'Connect', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Admin credential').inputValue(), '');
  assert.deepEqual(errors, []);
  console.log('Dashboard E2E passed: auth, documents/CAS/watch, jobs, cache, search, cron, events, console, docs, scope isolation, mobile and memory-only credentials.');
} finally {
  await browser?.close();
  child.kill('SIGTERM');
  if (child.exitCode === null && child.signalCode === null) await new Promise(resolve => child.once('exit', resolve));
  await rm(directory, { recursive: true, force: true });
}
